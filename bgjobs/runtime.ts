/**
 * Background job runtime: starting jobs, watching them, and calling back.
 *
 * A job runs as its own process group (`detached`), with stdout and stderr
 * redirected straight into its log file — so the job keeps running (and keeps
 * logging) even when pi exits, and a later session can adopt it again.
 *
 * The completion callback is a real user message (`sendUserMessage`) that
 * carries the exit code and the tail of the output, so the agent is woken up
 * when the job finishes instead of polling for it.
 */

import { spawn, type ChildProcess } from "node:child_process";
import * as fs from "node:fs";
import * as path from "node:path";
import type { ExtensionAPI, ExtensionContext } from "@earendil-works/pi-coding-agent";
import {
	exitFile,
	listRecords,
	loadRecord,
	logFile,
	newJobId,
	nameFromCommand,
	saveRecord,
	scriptFile,
	uniqueName,
} from "./records.ts";
import { isDisposed } from "./state.ts";
import type { JobRecord } from "./types.ts";

/** Child processes started by this pi process, keyed by job id. */
const live = new Map<string, ChildProcess>();
/** Kill timers for jobs with a timeout. */
const timeoutTimers = new Map<string, NodeJS.Timeout>();
/** Pollers for jobs adopted from an earlier pi process. */
const pollers = new Map<string, NodeJS.Timeout>();

const KILL_GRACE_MS = 3000;
const POLL_INTERVAL_MS = 2000;

/** Quote a string for a single-quoted shell word. */
function shellQuote(value: string): string {
	return `'${value.replace(/'/g, "'\\''")}'`;
}

/**
 * Write the wrapper script that runs the command and records its exit code.
 *
 * The command runs in a nested shell, so `exit 3` inside it is the command's
 * exit code and not the wrapper's — and the wrapper still gets to write the
 * exit-code file, which is how a job that outlived its pi process reports back.
 */
function writeWrapper(rec: JobRecord): void {
	const body = [
		"#!/bin/sh",
		`# bgjob ${rec.id} (${rec.name}) — generated by the bgjobs extension`,
		`sh -c ${shellQuote(rec.command)}`,
		"__bg_code=$?",
		`printf '%s' "$__bg_code" > ${shellQuote(rec.exitFile)}`,
		'exit "$__bg_code"',
		"",
	].join("\n");
	fs.writeFileSync(rec.scriptPath, body, { encoding: "utf-8", mode: 0o700 });
}

/** Read the last lines of a file (used for log tails). */
export function tailFile(file: string, maxLines: number, maxBytes: number): string {
	let fd: number | undefined;
	try {
		const size = fs.statSync(file).size;
		if (size === 0) return "";
		const start = Math.max(0, size - maxBytes);
		const length = size - start;
		fd = fs.openSync(file, "r");
		const buf = Buffer.alloc(length);
		fs.readSync(fd, buf, 0, length, start);
		let text = buf.toString("utf-8");
		const lines = text.split("\n");
		// The first line may be cut in half by the byte boundary: drop it.
		if (start > 0 && lines.length > 0) lines.shift();
		if (lines.length > maxLines) text = lines.slice(lines.length - maxLines).join("\n");
		return text.trimEnd();
	} catch {
		return "";
	} finally {
		if (fd !== undefined) {
			try {
				fs.closeSync(fd);
			} catch {
				// Nothing to do.
			}
		}
	}
}

/** The exit code the wrapper script recorded, if the job ended normally. */
function readExitCode(rec: JobRecord): number | null {
	try {
		const raw = fs.readFileSync(rec.exitFile, "utf-8").trim();
		if (raw === "") return null;
		const code = Number.parseInt(raw, 10);
		return Number.isFinite(code) ? code : null;
	} catch {
		return null;
	}
}

export function formatDuration(ms: number): string {
	if (ms < 1000) return `${Math.max(0, Math.round(ms))}ms`;
	if (ms < 60_000) return `${(ms / 1000).toFixed(1)}s`;
	const minutes = Math.floor(ms / 60_000);
	const seconds = Math.round((ms % 60_000) / 1000);
	return `${minutes}m ${seconds}s`;
}

/** A one-line description of the job's outcome. */
export function describeStatus(rec: JobRecord): string {
	switch (rec.status) {
		case "done":
			return "finished successfully";
		case "failed":
			return `failed (exit code ${rec.exitCode ?? "unknown"})`;
		case "killed":
			return `was killed${rec.signal ? ` (${rec.signal})` : ""}`;
		case "timeout":
			return `timed out after ${rec.timeoutSec ?? "?"}s`;
		case "lost":
			return "ended without reporting an exit code";
		default:
			return "is still running";
	}
}

/** The completion message that is pushed to the agent. */
export function buildCompletionText(rec: JobRecord): string {
	const duration = rec.finishedAt ? formatDuration(rec.finishedAt - rec.startedAt) : "unknown duration";
	const head = `[bgjob] Job "${rec.name}" ${describeStatus(rec)} (${duration}, id ${rec.id}).`;
	const tail = tailFile(rec.logPath, 20, 4000);
	return tail ? `${head}\n--- output (tail) ---\n${tail}` : head;
}

/** Push the completion message to the agent and to the user's UI. */
export function notifyDone(pi: ExtensionAPI, ctx: ExtensionContext, rec: JobRecord): void {
	const status = describeStatus(rec);
	try {
		ctx.ui.notify(`bgjob "${rec.name}": ${status}`, rec.status === "done" ? "info" : "warning");
	} catch {
		// UI may be unavailable (non-interactive modes).
	}
	try {
		pi.sendUserMessage(buildCompletionText(rec), { deliverAs: "steer" });
		rec.notifiedAt = Date.now();
		saveRecord(rec);
	} catch {
		// A missing send target leaves the record pending; the flush timer retries.
	}
}

/** Re-deliver completion messages that were never pushed (reload, busy turn, ...). */
export function flushPendingNotifications(pi: ExtensionAPI, ctx: ExtensionContext): void {
	if (isDisposed()) return;
	try {
		for (const rec of listRecords()) {
			if (rec.status === "running" || rec.notifiedAt) continue;
			pi.sendUserMessage(buildCompletionText(rec), { deliverAs: "steer" });
			rec.notifiedAt = Date.now();
			saveRecord(rec);
		}
	} catch {
		// Nothing to flush or the session is gone.
	}
}

/** Mark a job as finished and call back. */
export function finalizeJob(
	pi: ExtensionAPI,
	ctx: ExtensionContext,
	rec: JobRecord,
	code: number | null,
	signal: NodeJS.Signals | null,
): void {
	if (rec.status !== "running") return;
	rec.exitCode = code ?? readExitCode(rec);
	rec.signal = signal ?? null;
	rec.finishedAt = Date.now();
	if (rec.note === "timeout") rec.status = "timeout";
	else if (signal) rec.status = "killed";
	else if (rec.exitCode === 0) rec.status = "done";
	else if (rec.exitCode === null) rec.status = "lost";
	else rec.status = "failed";
	saveRecord(rec);
	notifyDone(pi, ctx, rec);
}

/** Stop a running job (its whole process group). */
export function killJob(rec: JobRecord, reason: "killed" | "timeout" = "killed"): boolean {
	if (rec.status !== "running") return false;
	if (rec.pid) {
		const pid = rec.pid;
		try {
			process.kill(-pid, "SIGTERM");
		} catch {
			try {
				process.kill(pid, "SIGTERM");
			} catch {
				// Already gone.
			}
		}
		setTimeout(() => {
			try {
				process.kill(-pid, "SIGKILL");
			} catch {
				// Already gone.
			}
		}, KILL_GRACE_MS).unref?.();
	}
	rec.note = reason;
	saveRecord(rec);
	return true;
}

/** Kill every running job of this session (used by the command). */
export function killAllJobs(reason: "killed" | "timeout" = "killed"): number {
	let count = 0;
	for (const rec of listRecords()) {
		if (rec.status !== "running") continue;
		if (killJob(rec, reason)) count++;
	}
	return count;
}

export interface StartJobOptions {
	command: string;
	name?: string;
	cwd?: string;
	timeoutSec?: number;
}

/**
 * Start a background job. Returns as soon as the process is spawned; the
 * agent is notified later, when the job ends.
 */
export function startJob(
	pi: ExtensionAPI,
	ctx: ExtensionContext,
	opts: StartJobOptions,
): { ok: true; rec: JobRecord } | { ok: false; error: string } {
	const command = opts.command.trim();
	if (!command) return { ok: false, error: "command is required" };

	const cwd = path.resolve(opts.cwd?.trim() || ctx.cwd);
	if (!fs.existsSync(cwd)) return { ok: false, error: `working directory does not exist: ${cwd}` };

	const id = newJobId();
	const taken = new Set(listRecords().map((r) => r.name.toLowerCase()));
	const rec: JobRecord = {
		id,
		name: uniqueName(opts.name?.trim() || nameFromCommand(command), taken),
		command,
		cwd,
		status: "running",
		exitCode: null,
		signal: null,
		startedAt: Date.now(),
		logPath: logFile(id),
		exitFile: exitFile(id),
		scriptPath: scriptFile(id),
		timeoutSec: opts.timeoutSec && opts.timeoutSec > 0 ? Math.round(opts.timeoutSec) : undefined,
	};

	writeWrapper(rec);

	let proc: ChildProcess;
	let fd: number | undefined;
	try {
		fd = fs.openSync(rec.logPath, "a");
		proc = spawn("/bin/sh", [rec.scriptPath], {
			cwd: rec.cwd,
			detached: true,
			stdio: ["ignore", fd, fd],
			env: process.env,
		});
	} catch (error) {
		if (fd !== undefined) {
			try {
				fs.closeSync(fd);
			} catch {
				// Nothing to do.
			}
		}
		return {
			ok: false,
			error: `failed to start job: ${error instanceof Error ? error.message : String(error)}`,
		};
	}
	// The child has its own copy of the log fd now.
	try {
		fs.closeSync(fd);
	} catch {
		// Nothing to do.
	}

	rec.pid = proc.pid;
	saveRecord(rec);
	live.set(id, proc);
	// The job outlives pi: do not hold the event loop open for it.
	proc.unref();

	let settled = false;
	const onDone = (code: number | null, signal: NodeJS.Signals | null) => {
		if (settled) return;
		settled = true;
		live.delete(id);
		const timer = timeoutTimers.get(id);
		if (timer) clearTimeout(timer);
		timeoutTimers.delete(id);
		finalizeJob(pi, ctx, rec, code, signal);
	};
	proc.on("exit", (code, signal) => onDone(code, signal));
	proc.on("error", (error) => {
		rec.note = rec.note ?? `failed: ${error.message}`;
		saveRecord(rec);
		onDone(null, null);
	});

	if (rec.timeoutSec) {
		timeoutTimers.set(
			id,
			setTimeout(() => {
				killJob(rec, "timeout");
			}, rec.timeoutSec * 1000),
		);
	}

	return { ok: true, rec };
}

/** True when a pid is alive. */
export function isPidAlive(pid: number | undefined): boolean {
	if (!pid) return false;
	try {
		process.kill(pid, 0);
		return true;
	} catch (error) {
		return (error as NodeJS.ErrnoException).code === "EPERM";
	}
}

/**
 * Adopt jobs that were still running when an earlier pi process ended.
 *
 * The job keeps running in its own process group, so a later session can pick
 * it up: the exit-code file tells us how it ended, and a poller watches for it.
 */
export function adoptOrphanJobs(pi: ExtensionAPI, ctx: ExtensionContext): void {
	for (const rec of listRecords()) {
		if (rec.status !== "running") continue;

		const code = readExitCode(rec);
		if (code !== null) {
			// It finished while we were away.
			finalizeJob(pi, ctx, rec, code, null);
			continue;
		}

		if (!isPidAlive(rec.pid)) {
			// Gone, and it never wrote an exit code: it was killed.
			finalizeJob(pi, ctx, rec, null, "SIGTERM");
			continue;
		}

		// Still alive: watch it until it ends.
		watchAdoptedJob(pi, ctx, rec);
	}
}

/** Poll an adopted job until it finishes (or its timeout expires). */
function watchAdoptedJob(pi: ExtensionAPI, ctx: ExtensionContext, rec: JobRecord): void {
	if (pollers.has(rec.id)) return;

	const poll = setInterval(() => {
		const current = loadRecord(rec.id);
		if (!current || current.status !== "running") {
			clearInterval(poll);
			pollers.delete(rec.id);
			return;
		}

		const code = readExitCode(current);
		if (code !== null) {
			clearInterval(poll);
			pollers.delete(current.id);
			finalizeJob(pi, ctx, current, code, null);
			return;
		}

		if (!isPidAlive(current.pid)) {
			clearInterval(poll);
			pollers.delete(current.id);
			finalizeJob(pi, ctx, current, null, "SIGTERM");
			return;
		}

		// The timeout still applies across sessions.
		if (current.timeoutSec && Date.now() - current.startedAt > current.timeoutSec * 1000) {
			clearInterval(poll);
			pollers.delete(current.id);
			killJob(current, "timeout");
		}
	}, POLL_INTERVAL_MS);
	pollers.set(rec.id, poll);
}

/** Stop tracking the jobs of this process (the session is going away). */
export function detachLiveJobs(): void {
	for (const timer of timeoutTimers.values()) clearTimeout(timer);
	timeoutTimers.clear();
	for (const poll of pollers.values()) clearInterval(poll);
	pollers.clear();
	live.clear();
}
